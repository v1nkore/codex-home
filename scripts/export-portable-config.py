#!/usr/bin/env python3
"""Export a safe, portable subset of Codex config.toml."""

from __future__ import annotations

import re
import sys
from pathlib import Path


TOP_LEVEL_KEYS = ("model", "model_reasoning_effort")
DESKTOP_KEYS = (
    "followUpQueueMode",
    "conversationDetailMode",
    "ambient-suggestions-enabled",
    "realtimeVoiceScreenContextEnabled",
)


ASSIGNMENT = re.compile(r"^([A-Za-z0-9_.-]+)\s*=\s*(.+)$")
PLUGIN_SECTION = re.compile(r'^\[plugins\."[^"\\]+"\]$')


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: export-portable-config.py INPUT OUTPUT")

    source = Path(sys.argv[1])
    destination = Path(sys.argv[2])
    output = [
        "# Portable, deliberately sanitized subset of ~/.codex/config.toml.",
        "# Generated by scripts/export-portable-config.py.",
        "",
    ]
    section = ""
    pending_section = ""

    for raw_line in source.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if line.startswith("[") and line.endswith("]"):
            section = line
            pending_section = line if PLUGIN_SECTION.match(line) or line == "[desktop]" else ""
            continue

        match = ASSIGNMENT.match(line)
        if not match:
            continue
        key, value = match.groups()

        allowed = (
            (not section and key in TOP_LEVEL_KEYS)
            or (PLUGIN_SECTION.match(section) is not None and key == "enabled" and value in {"true", "false"})
            or (section == "[desktop]" and key in DESKTOP_KEYS)
        )
        if not allowed:
            continue

        if pending_section:
            output.extend(["", pending_section])
            pending_section = ""
        output.append(f"{key} = {value}")

    destination.write_text("\n".join(output) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
